const NBSP = '\u00A0';

// Невидимый символ, запрещающий перенос в месте, где стоит. Ставим его после дефиса:
// неразрывного дефиса U+2011 может не быть в шрифте, а этот символ не рисуется вовсе.
// Цена: при копировании слова он уходит в буфер вместе с ним
const WORD_JOINER = '\u2060';

// Начало слова: начало строки, пробел (в том числе неразрывный), скобка или кавычка
const WORD_START = '(?<=^|[\\s(«„“"])';

// Предлоги, союзы и местоимения, которые не должны оставаться в конце строки:
// привязываются к следующему слову
const LEADING_WORDS = [
  'а', 'в', 'во', 'и', 'к', 'ко', 'о', 'об', 'обо', 'с', 'со', 'у', 'я',
  'без', 'до', 'для', 'за', 'из', 'изо', 'из-за', 'из-под', 'на', 'над', 'не', 'ни', 'но',
  'от', 'по', 'под', 'при', 'про', 'перед', 'через',
  'да', 'или', 'как', 'что', 'чем',
  'он', 'мы', 'вы',
];

// Частицы, которые не должны начинать строку: привязываются к предыдущему слову
const TRAILING_WORDS = ['же', 'ли', 'бы'];

// Сокращения перед названием или числом: «г. Москва», «ул. Ленина», «стр. 10»
const ABBREVIATIONS = ['г', 'гг', 'д', 'им', 'п', 'пп', 'рис', 'см', 'ст', 'стр', 'табл', 'тт', 'ул'];

// Счётные сокращения держатся и за число перед ними, и за слово после: «900 млн рублей»
const COUNT_WORDS = ['тыс', 'млн', 'млрд', 'трлн'];

// Незахватывающая группа, длинные варианты первыми, иначе «о» перехватит начало «об»/«от»
const alternation = (words: string[]) =>
  `(?:${[...words].sort((a, b) => b.length - a.length).join('|')})`;

const RULES: [RegExp, string][] = [
  // «и в сложной ситуации»: lookbehind не съедает пробел перед словом,
  // поэтому цепочки коротких слов обрабатываются за один проход
  [new RegExp(`${WORD_START}(${alternation(LEADING_WORDS)})\\s+`, 'giu'), `$1${NBSP}`],
  // «что же делать»
  [new RegExp(`\\s+(${alternation(TRAILING_WORDS)})(?=$|[\\s.,:;!?…»)])`, 'giu'), `${NBSP}$1`],
  // «900 млн», «5 лет», «20 °C», «10 %»
  [/(\d)\s+(?=[\p{L}%‰°₽$€])/gu, `$1${NBSP}`],
  // Разряды: «1 000 000»
  [/(\d)\s+(?=\d{3}(?!\d))/gu, `$1${NBSP}`],
  // «млн рублей», «тыс. рублей»
  [new RegExp(`${WORD_START}(${alternation(COUNT_WORDS)}\\.?)\\s+`, 'giu'), `$1${NBSP}`],
  // «г. Москва», «стр. 10». Не после числа — в «2024 г. Потом» точка закрывает
  // предложение — и не после «т.»: «и т. д. Далее»
  [new RegExp(`${WORD_START}(?<!\\d\\s)(?<!т\\.\\s)(${alternation(ABBREVIATIONS)})\\.\\s+`, 'giu'), `$1.${NBSP}`],
  // «т. е.», «т. д.», «т. п.», «т. к.»
  [/(?<=^|[\s(«„“"])(т)\.\s+(?=[едпк]\.)/giu, `$1.${NBSP}`],
  // «№ 5», «§ 12»
  [/([№§])\s*(?=\d)/gu, `$1${NBSP}`],
  // «А. С. Пушкин», «А.С. Пушкин»: инициал держится за следующий инициал или фамилию
  [/(?<=^|[\s(«„“"]|\p{Lu}\.)(\p{Lu}\.)\s+(?=\p{Lu}\.|\p{Lu}\p{Ll})/gu, `$1${NBSP}`],
  // «Пушкин А. С.»: фамилия держится за инициалы после неё
  [/(\p{Lu}\p{Ll}+)\s+(?=\p{Lu}\.\s?\p{Lu}\.)/gu, `$1${NBSP}`],
  // Тире не начинает строку: «шесть — в e-commerce»
  [/\s+([—–])/gu, `${NBSP}$1`],
];

// Адреса и почту не трогаем: невидимый символ внутри сломал бы скопированную ссылку.
// (?<!\S) начинает поиск только с начала слова — без него длинное слово
// перебирается с каждой позиции и время растёт квадратично
const ADDRESS = /((?<!\S)\S*(?:@|:\/\/|www\.)\S*)/u;

// Слово через дефис, в том числе уже обработанное: «e-commerce», «Ростов-на-Дону», «1990-х».
// Lookbehind в начале — по той же причине, что и у ADDRESS
const COMPOUND = new RegExp(`(?<![\\p{L}\\d])[\\p{L}\\d]+(?:-${WORD_JOINER}?[\\p{L}\\d]+)+`, 'gu');
const HYPHEN = new RegExp(`-${WORD_JOINER}?`, 'u');

// Перенос по дефису запрещён, если хотя бы с одной стороны кусок не длиннее трёх знаков.
// Слово разбирается целиком, поэтому повторный вызов даёт тот же результат
function joinHyphens(word: string): string {
  const parts = word.split(HYPHEN);
  return parts.slice(1).reduce(
    (result, part, i) => result + (parts[i].length <= 3 || part.length <= 3 ? `-${WORD_JOINER}` : '-') + part,
    parts[0],
  );
}

function formatPlain(text: string): string {
  return RULES
    .reduce((result, [pattern, replacement]) => result.replace(pattern, replacement), text)
    .replace(COMPOUND, joinHyphens);
}

/**
 * Расставляет неразрывные пробелы по правилам русской типографики, чтобы
 * короткие слова, числа и тире не отрывались от соседних слов при переносе.
 *
 * Через неё проходит весь видимый текст серверных компонентов, включая метаданные:
 * описание показывается в превью ссылок в мессенджерах и соцсетях. Правила — в CLAUDE.md.
 * Повторный вызов на уже обработанном тексте ничего не меняет.
 */
export function formatTypography(text: string): string {
  // split с группой в выражении: на нечётных местах оказываются сами адреса
  return text
    .split(ADDRESS)
    .map((part, index) => (index % 2 ? part : formatPlain(part)))
    .join('');
}
