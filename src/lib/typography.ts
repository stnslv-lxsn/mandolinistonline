const NBSP = '\u00A0';

// Предлоги, союзы и частицы, которые не должны оставаться в конце строки
const SHORT_WORDS = [
  'в', 'без', 'до', 'из', 'к', 'на', 'по', 'о', 'от', 'перед', 'при', 'через',
  'с', 'у', 'за', 'над', 'об', 'под', 'про', 'для', 'и', 'а', 'но', 'да', 'или',
  'не', 'ни', 'же', 'бы', 'ли', 'я', 'он', 'мы', 'вы',
];

// Длинные варианты идут первыми, иначе «о» перехватит начало «об»/«от»
const ALTERNATION = [...SHORT_WORDS].sort((a, b) => b.length - a.length).join('|');

// Короткое слово на границе (начало строки или пробел) + следующий за ним пробел.
// \s в JS включает и неразрывный пробел, поэтому второй проход видит границу.
const SHORT_WORD_RE = new RegExp(`(^|\\s)(${ALTERNATION})\\s+`, 'gi');

const REPLACEMENT = `$1$2${NBSP}`;

/**
 * Заменяет пробел после коротких слов на неразрывный, чтобы предлоги
 * не «висели» в конце строки.
 *
 * Проходов два: replace не начинает поиск внутри уже найденного совпадения,
 * поэтому цепочки вида «и в команде» обрабатываются только на втором проходе.
 */
export function formatTypography(text: string): string {
  return text.replace(SHORT_WORD_RE, REPLACEMENT).replace(SHORT_WORD_RE, REPLACEMENT);
}
